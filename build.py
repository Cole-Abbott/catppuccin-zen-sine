"""Rebuild the Sine styles from the frozen, unmodified upstream themes."""
from pathlib import Path
import base64
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent
FLAVORS = ['Latte', 'Frappe', 'Macchiato', 'Mocha']
ACCENTS = sorted(p.name for p in (ROOT / 'vendor/themes/Mocha').iterdir())

def selected(prop, value, choices, default):
    if value != default:
        return f'(-moz-pref("{prop}", "{value.lower()}"))'
    return '(' + ' and '.join(f'(not (-moz-pref("{prop}", "{v.lower()}")))' for v in choices if v != default) + ')'

def build():
    styles = {name: ['/* Catppuccin for Sine. Generated by build.py; see LICENSE and PROVENANCE.json. */\n'] for name in ['userChrome.css', 'userContent.css']}
    hashes = {}
    for flavor in FLAVORS:
        for accent in ACCENTS:
            folder = ROOT / 'vendor/themes' / flavor / accent
            for path in folder.iterdir():
                hashes[str(path.relative_to(ROOT))] = hashlib.sha256(path.read_bytes()).hexdigest()
            flavor_query = f'(-moz-pref("catppuccin.sine.flavor", "{flavor.lower()}"))'
            # An unset or invalid flavor follows light/dark appearance.
            auto = selected('catppuccin.sine.flavor', 'Auto', ['Auto'] + FLAVORS, 'Auto')
            if flavor in ['Latte', 'Mocha']:
                scheme = 'light' if flavor == 'Latte' else 'dark'
                flavor_query += f' or ({auto} and (prefers-color-scheme: {scheme}))'
            accent_query = selected('catppuccin.sine.accent', accent, ACCENTS, 'Mauve')
            for name, blocks in styles.items():
                source = (folder / name).read_text()
                pattern = r'@media\s*\(prefers-color-scheme:\s*(?:dark|light)\)\s*\{'
                source, count = re.subn(pattern, f'@media ({flavor_query}) and {accent_query} {{', source, count=1)
                assert count == 1, (flavor, accent, name)
                if name == 'userContent.css':
                    logo = next(folder.glob('*.svg'))
                    uri = 'data:image/svg+xml;base64,' + base64.b64encode(logo.read_bytes()).decode()
                    source, count = re.subn(r'url\("zen-logo-[^"]+"\),\s*url\("https://[^\"]+"\)', f'url("{uri}")', source)
                    assert count == 1, (flavor, accent)
                blocks.append(source + '\n')
    for name, blocks in styles.items():
        (ROOT / name).write_text('\n'.join(blocks))
    (ROOT / 'PROVENANCE.json').write_text(json.dumps({
        'repository': 'https://github.com/catppuccin/zen-browser',
        'commit': 'c855685442c6040c4dda9c8d3ddc7b708de1cbaa',
        'license': 'MIT', 'source_sha256': hashes,
        'changes': ['Replace outer appearance media queries with Sine flavor/accent preferences.', 'Embed the matching upstream SVG; remove the remote logo fallback.'],
    }, indent=2) + '\n')
    preferences = [
        {'type': 'dropdown', 'property': 'catppuccin.sine.flavor', 'label': 'Flavor', 'defaultValue': 'auto', 'placeholder': False,
         'options': [{'label': label, 'value': value} for label, value in [('Automatic (Latte / Mocha)', 'auto'), ('Latte', 'latte'), ('Frappé', 'frappe'), ('Macchiato', 'macchiato'), ('Mocha', 'mocha')]]},
        {'type': 'dropdown', 'property': 'catppuccin.sine.accent', 'label': 'Accent', 'defaultValue': 'mauve', 'placeholder': False,
         'options': [{'label': a, 'value': a.lower()} for a in ACCENTS]},
    ]
    (ROOT / 'preferences.json').write_text(json.dumps(preferences, indent=2) + '\n')

if __name__ == '__main__':
    build()
